-- scripts/postgres/001-schema.sql
--
-- Esquema PostgreSQL inicial para gestion_oficina.

BEGIN;

CREATE TABLE IF NOT EXISTS cuentas (
  codcuentacobranza TEXT PRIMARY KEY,
  idc TEXT NOT NULL,
  cliente TEXT NOT NULL,
  expediente TEXT,
  funcionario TEXT,
  gestor TEXT,

  mtodeuda_sol NUMERIC(20,4),
  mtodeudavencida_sol NUMERIC(20,4),
  dtp NUMERIC(20,4),

  estado_cartera TEXT,
  etapa_procesal TEXT,
  diasmora INTEGER,
  rango_mora TEXT,
  prioridad TEXT,
  segmentacion TEXT,
  descproducto TEXT,
  direccion TEXT,
  distrito TEXT,
  provincia TEXT,
  departamento TEXT,
  router TEXT,
  nivel_riesgo TEXT,
  tipo_juicio TEXT,
  nro_juicio TEXT,
  fec_demanda TEXT,
  supervisor_procesal TEXT,
  analista_procesal TEXT,
  fec_entrega_legajo_a_estudio TEXT,

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1)),

  fecha_ultima_actualizacion TEXT NOT NULL,

  codmoneda TEXT,
  deudatotal_monedaorigen NUMERIC(20,4),
  deudavencida_monedaorigen NUMERIC(20,4)
);

CREATE INDEX IF NOT EXISTS idx_cuentas_idc
  ON cuentas(idc);

CREATE TABLE IF NOT EXISTS gestiones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  codcuentacobranza TEXT,

  usuario_gestor_oficina TEXT NOT NULL,
  categoria TEXT,
  codigo_razon TEXT,

  fecha_hora TEXT NOT NULL,

  monto_compromiso NUMERIC(20,4),
  monto_pagado NUMERIC(20,4),

  fecha_promesa TEXT,
  observacion TEXT,
  segmentacion TEXT,
  telefono TEXT,
  moneda_monto_pagado TEXT,

  CONSTRAINT fk_gestiones_cuenta
    FOREIGN KEY (codcuentacobranza)
    REFERENCES cuentas(codcuentacobranza)
);

CREATE INDEX IF NOT EXISTS idx_gestiones_idc
  ON gestiones(idc);

CREATE TABLE IF NOT EXISTS telefonos (
  id_phone INTEGER PRIMARY KEY,

  idc TEXT NOT NULL,
  cic TEXT,
  phone TEXT NOT NULL,
  tipo_telefono TEXT NOT NULL,

  qtty_phone_ranking DOUBLE PRECISION,

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1)),

  creado_por TEXT,
  editado_por TEXT,
  fecha_modificacion TEXT,

  agregado_manualmente SMALLINT NOT NULL DEFAULT 0
    CHECK (agregado_manualmente IN (0, 1))
);

CREATE TABLE IF NOT EXISTS garantias (
  gar_codigo TEXT PRIMARY KEY,

  idc TEXT NOT NULL,
  cliente TEXT,
  tipo_garantia TEXT,
  descripcion TEXT,
  moneda TEXT,

  monto_comercial NUMERIC(20,4),
  monto_afectacion NUMERIC(20,4),
  monto_realizacion NUMERIC(20,4),

  funcionario TEXT,

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_garantias_idc
  ON garantias(idc);

CREATE TABLE IF NOT EXISTS apersonamiento (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  codcuentacobranza TEXT,
  cliente TEXT,
  desgrupofuncional TEXT,
  fec_asignacion_lgm TEXT,
  fecha_entrega TEXT,
  motivo TEXT,

  montodeudatotal NUMERIC(20,4),

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_apersonamiento_idc
  ON apersonamiento(idc);

CREATE TABLE IF NOT EXISTS promesas_pago (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  codcuentacobranza TEXT NOT NULL,

  tipo TEXT NOT NULL,
  moneda TEXT NOT NULL,

  monto_deuda_total NUMERIC(20,4),

  fecha_promesa TEXT NOT NULL,

  estado TEXT NOT NULL DEFAULT 'vigente',

  usuario_gestor_oficina TEXT NOT NULL,
  fecha_hora TEXT NOT NULL,

  gestion_id INTEGER,

  monto_prometido NUMERIC(20,4),
  modalidad_pago TEXT,
  observacion TEXT,

  monto_dolares NUMERIC(20,4),

  tipo_negociacion TEXT,
  beneficio TEXT,
  status_pdp TEXT,
  status_pago TEXT,

  numero_cuotas_aprobadas INTEGER,

  estudio TEXT,
  matriz TEXT,

  CONSTRAINT fk_promesas_cuenta
    FOREIGN KEY (codcuentacobranza)
    REFERENCES cuentas(codcuentacobranza),

  CONSTRAINT fk_promesas_gestion
    FOREIGN KEY (gestion_id)
    REFERENCES gestiones(id)
);

CREATE INDEX IF NOT EXISTS idx_promesas_idc
  ON promesas_pago(idc);

CREATE TABLE IF NOT EXISTS citas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  tipo TEXT NOT NULL,
  fecha_cita TEXT NOT NULL,
  observacion TEXT,

  estado TEXT NOT NULL DEFAULT 'pendiente',

  usuario_gestor_oficina TEXT NOT NULL,
  fecha_hora TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_citas_idc
  ON citas(idc);

CREATE TABLE IF NOT EXISTS historial_router (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  codcuentacobranza TEXT NOT NULL,

  fecha_registro TEXT NOT NULL,
  seguimiento TEXT NOT NULL,
  router TEXT NOT NULL,
  descripcion TEXT
);

CREATE INDEX IF NOT EXISTS idx_historial_router_idc
  ON historial_router(idc);

CREATE TABLE IF NOT EXISTS imports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  nombre_archivo TEXT NOT NULL,
  fecha_import TEXT NOT NULL,

  cuentas_nuevas INTEGER,
  cuentas_actualizadas INTEGER,
  cuentas_dadas_de_baja INTEGER
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  nombre_completo TEXT NOT NULL,

  gestor TEXT,

  rol TEXT NOT NULL DEFAULT 'gestor',

  debe_cambiar_contrasena SMALLINT NOT NULL DEFAULT 1
    CHECK (debe_cambiar_contrasena IN (0, 1)),

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1)),

  fecha_creacion TEXT NOT NULL,

  email TEXT,

  intentos_fallidos INTEGER NOT NULL DEFAULT 0,

  bloqueado_hasta TEXT
);

CREATE TABLE IF NOT EXISTS exportaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  fecha_hora TEXT NOT NULL,
  usuario TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS direcciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  idc TEXT NOT NULL,
  direccion TEXT NOT NULL,

  distrito TEXT,
  provincia TEXT,
  departamento TEXT,

  tipo TEXT NOT NULL DEFAULT 'Domicilio',
  fuente TEXT NOT NULL DEFAULT 'portafolio',

  creado_por TEXT,
  editado_por TEXT,

  fecha_modificacion TEXT NOT NULL,

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_direcciones_idc
  ON direcciones(idc);

CREATE TABLE IF NOT EXISTS whatsapp_numeros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  numero TEXT NOT NULL UNIQUE,
  propietario TEXT NOT NULL,

  propietario_tipo TEXT NOT NULL DEFAULT 'gestor',

  activo SMALLINT NOT NULL DEFAULT 1
    CHECK (activo IN (0, 1)),

  principal SMALLINT NOT NULL DEFAULT 0
    CHECK (principal IN (0, 1)),

  fecha_creacion TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_whatsapp_numeros_activo
  ON whatsapp_numeros(activo);

CREATE TABLE IF NOT EXISTS whatsapp_campanas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  fecha_creacion TEXT NOT NULL,
  usuario_creador TEXT,

  campana TEXT NOT NULL,
  gestor TEXT,

  desde TEXT NOT NULL,
  hasta TEXT NOT NULL,

  numero_salida TEXT NOT NULL,

  total_seleccionados INTEGER NOT NULL DEFAULT 0,
  total_preparados INTEGER NOT NULL DEFAULT 0,
  total_sin_telefono INTEGER NOT NULL DEFAULT 0,
  total_fallidos INTEGER NOT NULL DEFAULT 0,
  total_enviados INTEGER NOT NULL DEFAULT 0,

  estado TEXT NOT NULL DEFAULT 'PREPARADA'
);

CREATE INDEX IF NOT EXISTS idx_whatsapp_campanas_fecha
  ON whatsapp_campanas(fecha_creacion);

CREATE INDEX IF NOT EXISTS idx_whatsapp_campanas_estado
  ON whatsapp_campanas(estado);

CREATE TABLE IF NOT EXISTS whatsapp_campana_destinatarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  campana_id INTEGER NOT NULL,

  idc TEXT NOT NULL,
  cliente TEXT,
  gestor TEXT,

  telefono_destino TEXT,
  tipo_telefono TEXT,

  estado TEXT NOT NULL DEFAULT 'PREPARADO',

  error TEXT,
  fecha_procesamiento TEXT,

  mensaje TEXT,

  status_pdp TEXT,
  monto_pdp NUMERIC(20,4),
  moneda_pdp TEXT,
  fecha_pdp TEXT,

  duracion_ms INTEGER,
  tenor TEXT,

  CONSTRAINT fk_whatsapp_destinatarios_campana
    FOREIGN KEY (campana_id)
    REFERENCES whatsapp_campanas(id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_whatsapp_destinatarios_campana
  ON whatsapp_campana_destinatarios(campana_id);

CREATE INDEX IF NOT EXISTS idx_whatsapp_destinatarios_idc
  ON whatsapp_campana_destinatarios(idc);


COMMIT;